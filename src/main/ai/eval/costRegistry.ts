import {
  AI_FEATURE_IDS,
  DEFAULT_MODELS,
  OPENROUTER_DEFAULT_MODELS,
  inputBudget,
  outputBudget,
  priceFor,
  type AiFeatureId,
  type Tier
} from '@shared/ai'
import { AI_COST_NOTES } from '@shared/aiCostNotes'
import { AI_DATA_SHARING } from '@shared/aiSettings'
import { DEFAULT_BILLING_TERMS } from '@shared/cloudBilling'
import { PROMPT_CATALOGUE, PROMPT_VERSIONS, type PromptVersion } from '../prompts/catalogue'
import type { TokenRow } from './report'

/**
 * The AI cost registry (author request 2026-10-08): one row per AI feature with what it does, what
 * starts it, its current prompt, budgets, the token sizes the eval fixtures measure, and the
 * estimated cost per call on each provider's default models. Written to docs/AI-COST-REGISTRY.md by
 * `npm run eval:ai -- -u` next to the token report, so it can never drift from the code; the git
 * history of that file is the log of how each feature's cost changed.
 */

/** The version a feature asks for first: its newest non-regenerate prompt. */
function currentVersion(feature: AiFeatureId): PromptVersion | null {
  const versions = PROMPT_VERSIONS.filter((v) => PROMPT_CATALOGUE[v].feature === feature)
  const primary = versions.filter((v) => !v.includes('Regen'))
  return primary.at(-1) ?? versions.at(-1) ?? null
}

function median(values: number[]): number {
  const sorted = [...values].sort((a, b) => a - b)
  const mid = Math.floor(sorted.length / 2)
  return sorted.length % 2 === 1
    ? (sorted[mid] ?? 0)
    : ((sorted[mid - 1] ?? 0) + (sorted[mid] ?? 0)) / 2
}

/** USD to a short, comparable string: fractions of a cent keep four significant digits. */
export function formatUsd(usd: number): string {
  if (usd === 0) return '$0'
  if (usd >= 1) return `$${usd.toFixed(2)}`
  return `$${usd.toPrecision(3)}`
}

interface FeatureCost {
  feature: AiFeatureId
  version: PromptVersion | null
  tier: Tier | null
  typicalIn: number
  worstIn: number
  typicalOut: number
  worstOut: number
}

function costsFor(feature: AiFeatureId, rows: TokenRow[]): FeatureCost {
  const version = currentVersion(feature)
  const tier = version === null ? null : PROMPT_CATALOGUE[version].tier
  const totals = rows.filter((r) => r.version === version).map((r) => r.total)
  return {
    feature,
    version,
    tier,
    typicalIn: totals.length > 0 ? Math.round(median(totals)) : 0,
    worstIn: totals.length > 0 ? Math.max(...totals) : inputBudget(feature),
    typicalOut: AI_COST_NOTES[feature].typicalOutTokens,
    worstOut: outputBudget(feature)
  }
}

function perCall(model: string, inTok: number, outTok: number): number {
  return priceFor(model, inTok, outTok).costUsd
}

function cell(text: string): string {
  return text.replace(/\|/g, '\\|').replace(/\n/g, ' ')
}

export function renderCostRegistry(rows: TokenRow[]): string {
  const markup = DEFAULT_BILLING_TERMS.markup
  const lines: string[] = [
    '# AI cost registry',
    '',
    'Every AI feature in MythScribe, what starts it, and what one call costs. Generated by',
    '`npm run eval:ai -- -u` from the code (`src/main/ai/eval/costRegistry.ts`) and the hand-written',
    'notes in `src/shared/aiCostNotes.ts`; a new AI feature does not compile until it has a note. The',
    "git history of this file is the log of each feature's cost over time (author request 2026-10-08).",
    '',
    '- Tokens are the eval fixtures\' estimates (characters / 4): "typical" is the median fixture,',
    '  "worst" the largest fixture (or the input budget when a feature has no prompt). Output is the',
    "  note's typical estimate and the feature's `max_tokens` cap for the worst case.",
    `- Own key (OpenRouter) uses the default models: fast \`${OPENROUTER_DEFAULT_MODELS.fast}\`, strong \`${OPENROUTER_DEFAULT_MODELS.strong}\`. OpenAI uses fast \`${DEFAULT_MODELS.fast}\`, strong \`${DEFAULT_MODELS.strong}\`. Hosted is the OpenRouter cost plus the ${Math.round(markup * 100)}% markup.`,
    '- Estimates only: the ledger (Settings › AI › Usage history) and the developer tools record',
    '  real tokens and cost per request. Use them to correct the typical sizes here.',
    '',
    '## Per feature',
    '',
    '| Feature | What | Trigger | Prompt | Tier | In typical / worst | Out typical / cap | Own key (OpenRouter) typical · worst | Hosted typical | OpenAI typical | Calls per use | Typical per use (own key) |',
    '| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |'
  ]
  for (const feature of AI_FEATURE_IDS) {
    const c = costsFor(feature, rows)
    const note = AI_COST_NOTES[feature]
    const tier = c.tier ?? 'fast'
    const orModel = OPENROUTER_DEFAULT_MODELS[tier]
    const oaModel = DEFAULT_MODELS[tier]
    const orTypical = perCall(orModel, c.typicalIn, c.typicalOut)
    const orWorst = perCall(orModel, c.worstIn, c.worstOut)
    const hosted = orTypical * (1 + markup)
    const openai = perCall(oaModel, c.typicalIn, c.typicalOut)
    const perUse = orTypical * note.callsPerUse
    lines.push(
      `| \`${feature}\` | ${cell(AI_DATA_SHARING[feature].label)} | ${note.trigger} | ${c.version ?? '—'} | ${c.tier ?? '—'} | ${c.typicalIn} / ${c.worstIn} | ${c.typicalOut} / ${c.worstOut} | ${formatUsd(orTypical)} · ${formatUsd(orWorst)} | ${formatUsd(hosted)} | ${formatUsd(openai)} | ${note.callsPerUse} | ${formatUsd(perUse)} |`
    )
  }
  lines.push('', '## When each runs, and ideas to make it cheaper', '')
  for (const feature of AI_FEATURE_IDS) {
    const note = AI_COST_NOTES[feature]
    lines.push(`### \`${feature}\` — ${AI_DATA_SHARING[feature].label}`, '')
    lines.push(`- **When:** ${note.when}`)
    lines.push(`- **Ideas:** ${note.ideas}`, '')
  }
  return `${lines.join('\n').trimEnd()}\n`
}
