import { estimateTokens, inputBudget, outputBudget } from '@shared/ai'
import type { CompletionUsage } from '../providers/types'
import { PROMPT_CATALOGUE, type PromptVersion } from '../prompts/catalogue'
import type { EvalCase } from './fixtures'

/**
 * The eval harness's reports (F-5.12), pure over the cases and the live results so the
 * suite can pin the offline one to a committed file and print the live one.
 */

export interface TokenRow {
  version: PromptVersion
  since: string
  name: string
  note: string
  /** Estimated tokens of the system turn: the stable prefix provider caching applies to. */
  system: number
  /** Estimated tokens of the rest of the messages. */
  user: number
  /** The request path's own estimate over the whole prompt, what the input budget is checked against. */
  total: number
  inputBudget: number
  headroom: number
  maxTokens: number
  outputBudget: number
}

/** One row per case, in case order, estimated exactly as `runAiRequest` estimates. */
export function tokenRows(cases: EvalCase[]): TokenRow[] {
  return cases.map((c) => {
    const entry = PROMPT_CATALOGUE[c.version]
    const system = c.messages.filter((m) => m.role === 'system')
    const rest = c.messages.filter((m) => m.role !== 'system')
    const total = estimateTokens(c.messages.map((m) => m.content).join('\n'))
    const budget = inputBudget(entry.feature)
    return {
      version: c.version,
      since: entry.since,
      name: c.name,
      note: c.note,
      system: estimateTokens(system.map((m) => m.content).join('\n')),
      user: estimateTokens(rest.map((m) => m.content).join('\n')),
      total,
      inputBudget: budget,
      headroom: budget - total,
      maxTokens: c.maxTokens,
      outputBudget: outputBudget(entry.feature)
    }
  })
}

const TOKEN_REPORT_HEAD = [
  '# Prompt token report (F-5.12)',
  '',
  'Generated by `npm run eval:ai -- -u` from the cases in `src/main/ai/eval/fixtures.ts`. Token',
  'counts are `estimateTokens` (characters / 4), the same pre-flight estimate the request path',
  'checks the input budget against; the ledger records the provider\'s real count. "System" is the',
  'stable prefix provider caching applies to, "User" the rest.',
  '',
  'A changed row for a shipped version means its prompt file, a cap it reads, or a fixture changed.',
  'Prompt versions are immutable once shipped: a prompt change is a new `<feature>.v<N+1>.ts` with',
  'its own golden test and its own rows here. The diff of this file in a change is its token delta.',
  ''
]

/** The committed token report as Markdown. */
export function renderTokenReport(rows: TokenRow[]): string {
  const header = [
    'Prompt',
    'Since',
    'Case',
    'System',
    'User',
    'Total',
    'Budget',
    'Headroom',
    'max_tokens',
    'Cap',
    'Exercises'
  ]
  const cells = rows.map((r) => [
    r.version,
    r.since,
    r.name,
    String(r.system),
    String(r.user),
    String(r.total),
    String(r.inputBudget),
    String(r.headroom),
    String(r.maxTokens),
    String(r.outputBudget),
    r.note
  ])
  return `${[...TOKEN_REPORT_HEAD, ...markdownTable(header, cells)].join('\n')}\n`
}

export interface LiveResult {
  version: PromptVersion
  name: string
  model: string
  /** The answer after the feature's post-processing (prose) or as returned (JSON). */
  answer: string
  estimatedIn: number
  usage: CompletionUsage
  costUsd: number
  verdict:
    | { kind: 'fidelity'; ok: boolean; violations: string[] }
    | { kind: 'unscored' }
    | { kind: 'json'; ok: boolean; problem: string | null }
}

/** The live report: one row per answer, then the pass rate, the estimate's accuracy, and the spend. */
export function renderLiveReport(results: LiveResult[], at: Date): string {
  const header = ['Prompt', 'Case', 'Model', 'Verdict', 'In (est.)', 'Out', 'Cost USD', 'Answer']
  const cells = results.map((r) => [
    r.version,
    r.name,
    r.model,
    verdictText(r.verdict),
    `${r.usage.inputTokens} (${r.estimatedIn})`,
    String(r.usage.outputTokens),
    r.costUsd.toFixed(5),
    oneLine(r.answer, 80)
  ])
  const scored = results.filter((r) => r.verdict.kind !== 'unscored')
  const passed = scored.filter((r) => r.verdict.kind !== 'unscored' && r.verdict.ok).length
  const estimated = results.reduce((sum, r) => sum + r.estimatedIn, 0)
  const actual = results.reduce((sum, r) => sum + r.usage.inputTokens, 0)
  const cost = results.reduce((sum, r) => sum + r.costUsd, 0)
  const ratio = estimated === 0 ? 'n/a' : (actual / estimated).toFixed(2)
  return `${[
    `# Live prompt eval (${at.toISOString()})`,
    '',
    ...markdownTable(header, cells),
    '',
    `Scored ${passed} of ${scored.length} answers clean (${results.length - scored.length} unscored).`,
    `Actual input tokens over the estimate: ${ratio} (${actual} of ${estimated} estimated).`,
    `Spent ${cost.toFixed(5)} USD over ${results.length} requests.`
  ].join('\n')}\n`
}

function verdictText(verdict: LiveResult['verdict']): string {
  if (verdict.kind === 'unscored') return 'unscored'
  if (verdict.kind === 'fidelity') return verdict.ok ? 'clean' : verdict.violations.join('; ')
  return verdict.ok ? 'valid' : (verdict.problem ?? 'invalid')
}

function oneLine(text: string, max: number): string {
  const flat = text.replace(/\s+/g, ' ').replace(/\|/g, '\\|').trim()
  return flat.length > max ? `${flat.slice(0, max - 1)}…` : flat
}

/** A Markdown table with padded columns, so the committed file reads as a table in a diff too. */
export function markdownTable(header: string[], rows: string[][]): string[] {
  const widths = header.map((h, i) =>
    Math.max(h.length, ...rows.map((row) => (row[i] ?? '').length))
  )
  const line = (cells: string[]): string =>
    `| ${cells.map((cell, i) => cell.padEnd(widths[i] ?? 0)).join(' | ')} |`
  return [
    line(header),
    `| ${widths.map((w) => '-'.repeat(w)).join(' | ')} |`,
    ...rows.map((row) => line(header.map((_, i) => row[i] ?? '')))
  ]
}
