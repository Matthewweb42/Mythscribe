/** The message a channel of the other memory is refused with. */
export const OTHER_MEMORY_MESSAGE = 'This project uses the other story memory'

/**
 * Throws VALIDATION when `channel` belongs to the story memory the open project does not run;
 * `memory` null (no project open) passes, and the handler answers NO_PROJECT as before.
 */
export function assertChannelMemory(channel: Channel, memory: StoryMemoryVersion | null): void {
  const needs = CHANNEL_MEMORY[channel]
  if (needs === 'any' || memory === null || needs === memory) return
  throw new AppError('VALIDATION', OTHER_MEMORY_MESSAGE, { channel, memory })
}
